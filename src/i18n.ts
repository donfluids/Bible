export const NATIVE_BIBLE_NAME: Partial<Record<string, string>> = { MAL: 'സത്യവേദപുസ്തകം 1910', TAM: 'இண்டியன் ரிவைஸ்டு வெர்ஸன்', HIN: 'इंडियन रिवाइज्ड वर्जन' };

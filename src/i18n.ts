const TABLES: Record<Language, Record<StringKey, string>> = { en, ml, ta };

export function translate(language: Language, key: StringKey, params?: Record<string, string | number>): string {
  let text = TABLES[language][key] ?? en[key];
  if (params) for (const [k, v] of Object.entries(params)) text = text.split(`{${k}}`).join(String(v));
  return text;
}

/** Returns t(key, params) for the interface language in settings. */
export function useT(): (key: StringKey, params?: Record<string, string | number>) => string {
  const display = useDisplaySettings();
  if (!display) throw new Error('useT must be used inside SettingsProvider');
  const lang = display.language;
  return useCallback((key: StringKey, params?: Record<string, string | number>) => translate(lang, key, params), [lang]);
}

/** Heading for how a translation renders a word: "In the KJV", "സത്യവേദപുസ്തകത്തിൽ", "IRV-இல்". */
export function renderingsLabel(language: Language, id: string): string {
  if (language === 'ml') return id === 'MAL' ? 'സത്യവേദപുസ്തകത്തിൽ' : id === 'KJV' ? 'KJV-യിൽ' : id === 'WEB' ? 'WEB-ൽ' : id;
  if (language === 'ta') return id === 'TAM' ? 'IRV-இல்' : `${id}-இல்`;
  return id === 'MAL' ? 'In Sathyavedapusthakam' : id === 'TAM' ? 'In the Tamil IRV' : `In the ${id}`;
}

/** Display name of a translation in the interface language. */
export function translationName(language: Language, id: string): string {
  if (id === 'MAL') return language === 'ml' ? 'സത്യവേദപുസ്തകം 1910' : 'Sathyavedapusthakam 1910 (Malayalam)';
  if (id === 'TAM') return language === 'ta' ? 'இண்டியன் ரிவைஸ்டு வெர்ஸன்' : 'Indian Revised Version (Tamil)';
  if (id === 'KJV') return language === 'ml' ? 'കിംഗ് ജെയിംസ് വേർഷൻ' : language === 'ta' ? 'கிங் ஜேம்ஸ் வெர்ஸன்' : 'King James Version';
  if (id === 'WEB') return language === 'ml' ? 'വേൾഡ് ഇംഗ്ലീഷ് ബൈബിൾ' : language === 'ta' ? 'வேர்ல்டு இங்கிலீஷ் பைபிள்' : 'World English Bible';
  if (id === 'BSB') return 'Berean Standard Bible';
  return id;
}
